import { writeFile } from 'node:fs/promises'
import { load } from 'cheerio'

const source = 'https://www.nnk.gov.hu/index.php/kornyezetegugy/kornyezetegeszsegugyi-laboratoriumi-osztaly/vizhigienes-laboratorium/furdoviz/termeszetes-furdoviz/tajekoztato-fuzetek.html'
const read = async url => {
  const response = await fetch(url, { signal: AbortSignal.timeout(30000) })
  if (!response.ok) throw new Error(`Source HTTP ${response.status}`)
  return load(await response.text())
}
const index = await read(source)
const urls = [...new Set(index('a').toArray().map(node => index(node).attr('href')).filter(href => href?.includes('tajekoztato-fuzetek/')).map(href => new URL(href, source).href))]
const names = {}
for (const url of urls) {
  const page = await read(url)
  for (const node of page('a').toArray()) {
    const match = page(node).text().trim().match(/^(.*?),?\s+(HUBW_\d+)\.pdf$/i)
    if (!match) continue
    const [, name, id] = match
    if (names[id] && names[id] !== name) throw new Error(`Conflicting names: ${id}`)
    names[id] = name
  }
}
if (Object.keys(names).length < 100) throw new Error('Unexpectedly few official names')
const records = Object.fromEntries(Object.entries(names).sort().map(([id, name]) => [id, { nativeLanguage: 'hu', names: { hu: { name, sourceUrl: source, verifiedOn: new Date().toISOString().slice(0,10) } }, aliases: [] }]))
const output = `// Generated by scripts/generate-hungarian-location-names.mjs.\n// Official NNGYK bathing-water leaflet names, matched by HUBW identifier.\n// Source: ${source}\n// Retrieved: ${new Date().toISOString().slice(0, 10)}\nexport const LOCATION_NAME_RECORDS = ${JSON.stringify(records, null, 2)}\nexport const HUNGARIAN_LOCATION_NAMES = Object.fromEntries(Object.entries(LOCATION_NAME_RECORDS).map(([id, record]) => [id, record.names.hu.name]))\n`
await writeFile(new URL('../src/hungarianLocationNames.generated.js', import.meta.url), output)
console.log(`Saved ${Object.keys(names).length} official display names.`)
