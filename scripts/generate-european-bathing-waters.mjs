import { writeFile, rename } from 'node:fs/promises'
import { pathToFileURL } from 'node:url'

export const ENDPOINT = 'https://water.discomap.eea.europa.eu/arcgis/rest/services/BathingWater/BathingWater_Dyna_WM_2025/MapServer/14/query'
export function normalizeEuropeanSite({ attributes: a }) {
  if (!a || !['Coastal', 'Lake'].includes(a.bwWaterCategory) || !a.bathingWaterIdentifier || !a.bathingWaterName
    || !Number.isFinite(a.latitude) || !Number.isFinite(a.longitude)
    || a.latitude < 27 || a.latitude > 72 || a.longitude < -32 || a.longitude > 45) return null
  return [a.bathingWaterIdentifier, a.bathingWaterName, a.countryName, a.countryCode,
    a.latitude, a.longitude, ['Excellent', 'Good', 'Sufficient', 'Poor'].includes(a.qualityStatus) ? a.qualityStatus : 'Unclassified', a.bwWaterCategory === 'Lake' ? 'lake' : 'coastal']
}

async function generate() {
  const sites = new Map()
  for (let offset = 0; ; offset += 2000) {
    const url = new URL(ENDPOINT)
    url.search = new URLSearchParams({ where: '1=1', outFields: '*', returnGeometry: 'false', orderByFields: 'OBJECTID', resultOffset: String(offset), resultRecordCount: '2000', f: 'json' })
    const response = await fetch(url, { signal: AbortSignal.timeout(60000) })
    if (!response.ok) throw new Error(`EEA HTTP ${response.status}`)
    const data = await response.json()
    if (data.error || !Array.isArray(data.features)) throw new Error(JSON.stringify(data.error ?? 'Invalid EEA response'))
    for (const feature of data.features) {
      const row = normalizeEuropeanSite(feature)
      if (row) sites.set(row[0], row)
    }
    if (!data.exceededTransferLimit) break
    if (!data.features.length) throw new Error('Empty EEA page with more results expected')
  }
  if (sites.size < 1000) throw new Error(`Unexpectedly small bathing-water catalogue: ${sites.size}`)
  const rows = [...sites.values()].sort((a, b) => a[2].localeCompare(b[2]) || a[1].localeCompare(b[1]))
  const date = new Date().toISOString().slice(0, 10)
  const content = `// Generated by scripts/generate-european-bathing-waters.mjs.\n// Source: EEA; bathing waters data and coordinates: reporting national authorities.\n// Coastal and lake sites in Europe, including Atlantic islands; classification season 2025.\nexport const EUROPE_CATALOG_UPDATED_ON = '${date}'\nconst ROWS = ${JSON.stringify(rows)}\nexport const EUROPEAN_BATHING_WATERS = ROWS.map(([officialId, name, nation, countryCode, latitude, longitude, classification, waterType]) => ({\n  id: 'eea-' + officialId, officialId, name, area: nation, nation, countryCode, latitude, longitude, classification, waterType,\n  classificationYear: 2025, catalogUpdatedOn: EUROPE_CATALOG_UPDATED_ON, source: 'eea', seaBearing: null, riskLevel: null, heavyRainRisk: null, marineModelSupported: waterType === 'coastal',\n}))\n`
  const target = new URL('../src/europeanBathingWaters.generated.js', import.meta.url)
  const temporary = new URL('../src/europeanBathingWaters.generated.js.tmp', import.meta.url)
  await writeFile(temporary, content)
  await rename(temporary, target)
  console.log(`Generated ${rows.length} bathing sites in ${new Set(rows.map(row => row[2])).size} countries.`)
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) await generate()
