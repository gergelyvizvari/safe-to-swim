import { writeFile } from 'node:fs/promises'
import { load } from 'cheerio'
const source = 'https://www.idokep.hu/webkamera/tag/balaton'
async function page(url) {
  const response = await fetch(url, { signal: AbortSignal.timeout(20000) })
  if (!response.ok) throw new Error(`Camera source HTTP ${response.status}`)
  return load(await response.text())
}
const index = await page(source)
const links = [...new Set(index('a[user]').toArray().map(node => new URL(index(node).attr('href'), source).href))]
const cameras = []
for (let offset = 0; offset < links.length; offset += 4) {
  const batch = await Promise.all(links.slice(offset, offset + 4).map(async pageUrl => {
    const $ = await page(pageUrl)
    const [latitude, longitude] = ($('meta[name="geo.position"]').attr('content') ?? '').split(';').map(Number)
    const name = $('title').text().replace(/\s+webkamera.*$/i, '').trim()
    if (!name || !Number.isFinite(latitude) || !Number.isFinite(longitude) || latitude < 46.5 || latitude > 47.2 || longitude < 17 || longitude > 18.3) return null
    return { id: `idokep-${pageUrl.split('/').at(-1)}`, name, latitude, longitude, sourceName: 'Időkép', pageUrl, waterBodyId: 'balaton', verifiedOn: new Date().toISOString().slice(0,10) }
  }))
  cameras.push(...batch.filter(Boolean))
}
if (cameras.length < 20) throw new Error('Unexpectedly few geolocated cameras')
await writeFile(new URL('../src/balatonWebcams.generated.js', import.meta.url), `// Generated by scripts/generate-balaton-webcams.mjs.\n// Source: ${source}; coordinates from each camera's geo.position metadata.\n// Links only; a verified listing does not guarantee that a camera is online.\nexport const BALATON_WEBCAMS = ${JSON.stringify(cameras, null, 2)}\n`)
console.log(`Saved ${cameras.length} geolocated camera links.`)
